"""Writes test/com/andrew/insighthud/RouterTestData.java: a 4x4 street grid as one routing tile, built with the real
encoder so the Java decoder is checked against it. Run from the android directory: python test/make_router_tile.py

Nodes are numbered 100 + row * 4 + col; rows run north, columns east, 0.001 degrees apart (about 111 m / 82 m).
Streets: "Row 0".."Row 3" run east-west, "Col 0".."Col 3" north-south. Col 3 is one-way northbound.
No left turn from Col 1 into Row 2 heading north (node 109 -> 113 is banned after coming from 105... see BAN).
"""
import base64
import math
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from build_route_graph import bearing_byte, encode_tile  # noqa: E402

LAT0, LON0, STEP = 420_010_000, -729_990_000, 10_000  # 42.001, -72.999, 0.001 degrees


def node(r, c):
    return 100 + r * 4 + c


def at(r, c):
    return LAT0 + r * STEP, LON0 + c * STEP


def edge(a, b, name):
    (la, oa), (lb, ob) = at(*a), at(*b)
    length = math.hypot((lb - la) * 1e-7 * 110574, (ob - oa) * 1e-7 * 111320 * math.cos(math.radians(la * 1e-7)))
    cost = length / 11.0
    return (node(*a), la, oa, node(*b), lb, ob, cost, length, 6, 0,
            bearing_byte(la, oa, lb, ob), bearing_byte(la, oa, lb, ob), name, [])


edges = []
for r in range(4):
    for c in range(3):
        edges.append(edge((r, c), (r, c + 1), f"Row {r}"))
        edges.append(edge((r, c + 1), (r, c), f"Row {r}"))
for c in range(4):
    for r in range(3):
        edges.append(edge((r, c), (r + 1, c), f"Col {c}"))
        if c != 3:
            edges.append(edge((r + 1, c), (r, c), f"Col {c}"))
# No going straight north on Col 0 through (2,0) when arriving from (1,0).
BAN = {(node(1, 0), node(2, 0), node(3, 0))}
blob = encode_tile(edges, BAN)
out = pathlib.Path(__file__).parent / "com" / "andrew" / "insighthud" / "RouterTestData.java"
encoded = base64.b64encode(blob).decode()
chunks = [encoded[i:i + 100] for i in range(0, len(encoded), 100)]
body = "\n".join(f'        + "{chunk}"' for chunk in chunks)
out.write_text(f"""package com.andrew.insighthud;

/** Generated by test/make_router_tile.py: a 4x4 street grid as one routing tile (level 0, x 428, y 528). */
final class RouterTestData {{
    static final String TILE = ""
{body};
}}
""")
print(out, len(blob), "bytes,", len(edges), "edges")
